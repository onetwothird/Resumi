/**
 * Resume template registry.
 *
 * Every template is metadata + a declarative `TemplateDef`. The def is
 * rendered by `ResumeRenderer` (single source of truth), so adding a new
 * template here is enough to make it selectable, editable and printable.
 *
 * The legacy layout ids (`classic`, `modern`, `banking`, …) are preserved
 * as real templates so resumes saved before this library still render.
 */

import {
  ResumeTemplate,
  TemplateDef,
  CareerLevel,
  TemplateStyle,
  Category,
  SectionKey,
} from "./types";

/* ── Shared section orders ──────────────────────────────────────────── */

const S_ALL: SectionKey[] = ["summary", "experience", "education", "skills", "certifications"];
const S_EDU_FIRST: SectionKey[] = ["education", "summary", "skills", "experience", "certifications"];
const S_SKILLS_FIRST: SectionKey[] = ["skills", "summary", "experience", "education", "certifications"];
const S_SUMMARY_EXP: SectionKey[] = ["summary", "experience", "education", "certifications", "skills"];
const MAIN_STD: SectionKey[] = ["summary", "experience", "education"];
const SIDEBAR_KS: SectionKey[] = ["skills", "certifications"];

/* ── Def builders ───────────────────────────────────────────────────── */

type DefPartial = Omit<TemplateDef, "layout" | "sidebar" | "sidebarHeader" | "sections"> & {
  sections?: SectionKey[];
};

const single = (p: DefPartial): TemplateDef => ({
  layout: "single",
  ...p,
  sections: p.sections ?? S_ALL,
});

const splitL = (p: DefPartial & { sidebarWidth?: number; sidebarHeader?: boolean }): TemplateDef => ({
  layout: "split",
  sidebar: "left",
  ...p,
  sections: p.sections ?? S_ALL,
  sidebarHeader: p.sidebarHeader ?? true,
  sidebarWidth: p.sidebarWidth ?? 33,
});

const splitR = (p: DefPartial & { sidebarWidth?: number; sidebarHeader?: boolean }): TemplateDef => ({
  layout: "split",
  sidebar: "right",
  ...p,
  sections: p.sections ?? S_ALL,
  sidebarHeader: p.sidebarHeader ?? true,
  sidebarWidth: p.sidebarWidth ?? 33,
});

interface TplInput {
  id: string;
  name: string;
  category: Category;
  industry: string;
  useCase: string;
  description: string;
  careerLevel: CareerLevel[];
  professions: string[];
  atsFriendly: boolean;
  style: TemplateStyle;
  layoutLabel: "One Column" | "Two Column";
  def: TemplateDef;
}

const t = (p: TplInput): ResumeTemplate => ({
  id: p.id,
  name: p.name,
  category: p.category,
  industry: p.industry,
  useCase: p.useCase,
  description: p.description,
  careerLevel: p.careerLevel,
  professions: p.professions,
  atsFriendly: p.atsFriendly,
  style: p.style,
  layoutLabel: p.layoutLabel,
  def: p.def,
});

